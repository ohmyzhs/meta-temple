/* ───────── 응답 생성 ───────── */
function hasBatchim(word) {
  const c = word.charCodeAt(word.length - 1);
  return c >= 0xac00 && c <= 0xd7a3 && (c - 0xac00) % 28 !== 0;
}
const josa = (w, withB, withoutB) => w + (hasBatchim(w) ? withB : withoutB);

const ECHO = [
  (w) => `“${w}”, 그 한마디를 가만히 받아 둡니다.`,
  (w) => `${josa(w, '이라는', '라는')} 말씀에 잠시 머물러 봅니다.`,
  (w) => `말씀하신 ${josa(w, '을', '를')} 함께 조용히 바라보지요.`
];

const verseLine = (id) => {
  const c = CARD[id];
  return `“${c.quote}” — ${c.source}`;
};

function pickFresh(list, usedTexts) {
  const fresh = list.filter((x) => !usedTexts.some((u) => u.includes(x)));
  const pool = fresh.length ? fresh : list.filter((x) => !usedTexts[usedTexts.length - 1]?.includes(x));
  const from = pool.length ? pool : list;
  return from[Math.floor(Math.random() * from.length)];
}

/**
 * 로컬 선사 응답. history: [{role:'user'|'monk', text, verse?}]
 * 반환 { reply, verse, theme, crisis? }
 * 의료·법률 판단은 하지 않는다. 위기 신호가 보이면 무엇보다 먼저 109 를 안내한다.
 */
export function localMonkResponse(text, history = []) {
  const raw = String(text || '').trim();
  if (isCrisisText(raw)) return { ...CRISIS_REPLY, theme: 'crisis' };

  const flat = raw.replace(/\s+/g, '');
  let best = MONK_KB[MONK_KB.length - 1];
  let bestScore = 0;
  let echoWord = null;
  for (const theme of MONK_KB) {
    const hits = theme.keys.filter(([k]) => flat.includes(k));
    if (hits.length > bestScore) {
      best = theme;
      bestScore = hits.length;
      echoWord = hits.find(([, w]) => w)?.[1] || null;
    }
  }

  const monkReplies = history.filter((h) => h.role === 'monk').map((h) => h.text || '');
  const monkVerses = history.filter((h) => h.role === 'monk').map((h) => h.verse || '');
  const body = pickFresh(best.replies, monkReplies);
  const verse = pickFresh(best.verses.map(verseLine), monkVerses);

  let reply = body;
  if (!raw) {
    reply = '찻물이 알맞게 우러났습니다. 서두르지 말고 숨을 한 번 고른 뒤, 떠오르는 만큼만 들려주세요.';
  } else if (echoWord) {
    reply = `${ECHO[monkReplies.length % ECHO.length](echoWord)} ${body}`;
  }
  return { reply, verse, theme: best.id };
}
